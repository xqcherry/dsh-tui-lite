export type I18nKey = keyof typeof dict
export type I18nParams = Record<string, string | number>

const pluralRules = new Intl.PluralRules('en')

function pickText(text: I18nText | undefined, params: I18nParams): string | undefined {
  if (text === undefined || typeof text === 'string') return text
  const count = Number(params.count)
  return pluralRules.select(Number.isFinite(count) ? count : 0) === 'one' ? text.one : text.other
}

function substitute(template: string, params: I18nParams): string {
  return template.replace(/\{\{(\w+)\}\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  )
}

/** Resolve an English message, leaving missing keys and parameters visible. */
export function t(key: I18nKey, params: I18nParams = {}): string {
  return substitute(pickText(dict[key], params) ?? key, params)
}

/** Resolve a computed key, falling back to the caller's authoritative text. */
export function tOr(key: string, fallback: string, params: I18nParams = {}): string {
  const entry = (dict as Record<string, I18nText>)[key]
  return substitute(pickText(entry, params) ?? fallback, params)
}

